function testExperimentProgressCallback()

    Env = createTestEnvironment('2loops', 30, 2.5, 6, 7);
    cleanupObj = onCleanup(Env.Release); %#ok<NASGU>

    d = Env.d;
    Problem = Env.Problem;
    Config = Env.Config;

    Opt = struct( ...
        'NumberOfRuns', 2, ...
        'Algorithms', {{'GA', 'PSO'}}, ...
        'ExperimentSeed', 12345, ...
        'CacheMode', 'PerRun');

    Reports = struct( ...
        'Algorithm', {}, ...
        'Generation', {}, ...
        'MaxGenerations', {}, ...
        'BestCost', {}, ...
        'Feasible', {}, ...
        'Convergence', {}, ...
        'RunIndex', {}, ...
        'NumberOfRuns', {}, ...
        'RunLabel', {});

    Opt.ProgressCallback = @captureProgress;

    R = runExperiment(d, Problem, Config, Opt);

    % Both algorithms and both runs should report progress.
    assert(~isempty(Reports), ...
        'No experiment progress reports were received.');

    algorithms = {Reports.Algorithm};
    assert(any(strcmp(algorithms, 'GA')), ...
        'No GA progress reports were received.');
    assert(any(strcmp(algorithms, 'PSO')), ...
        'No PSO progress reports were received.');

    for a = {'GA', 'PSO'}

        algorithm = a{1};

        for r = 1:Opt.NumberOfRuns

            idx = strcmp(algorithms, algorithm) & ...
                  [Reports.RunIndex] == r;

            RunReports = Reports(idx);

            assert(~isempty(RunReports), ...
                '%s run %d produced no progress reports.', ...
                algorithm, r);

            generations = [RunReports.Generation];

            assert(generations(1) == 1, ...
                '%s run %d did not report generation 1.', ...
                algorithm, r);

            assert(generations(end) == Config.MaxGen, ...
                '%s run %d did not report the last generation.', ...
                algorithm, r);

            assert(all([RunReports.MaxGenerations] == Config.MaxGen), ...
                '%s run %d reported incorrect MaxGenerations.', ...
                algorithm, r);

            assert(all([RunReports.NumberOfRuns] == Opt.NumberOfRuns), ...
                '%s run %d reported incorrect NumberOfRuns.', ...
                algorithm, r);

            expectedLabel = sprintf('%s run %d/%d', ...
                algorithm, r, Opt.NumberOfRuns);

            assert(all(strcmp({RunReports.RunLabel}, expectedLabel)), ...
                '%s run %d has an incorrect RunLabel.', ...
                algorithm, r);

            assert(all(isfinite([RunReports.BestCost])), ...
                '%s run %d reported a non-finite BestCost.', ...
                algorithm, r);

            assert(all(arrayfun(@(x) ...
                islogical(x.Feasible) && isscalar(x.Feasible), ...
                RunReports)), ...
                '%s run %d reported an invalid Feasible value.', ...
                algorithm, r);

            assert(all(arrayfun(@(x) ...
                isnumeric(x.Convergence) && ...
                isvector(x.Convergence) && ...
                numel(x.Convergence) == x.Generation && ...
                all(isfinite(x.Convergence)) && ...
                x.Convergence(end) == x.BestCost, ...
                RunReports)), ...
                '%s run %d reported invalid convergence history.', ...
                algorithm, r);

        end

        % Ensure the experiment still stores successful results.
        Runs = R.Results.(algorithm).Runs;

        assert(all(strcmp({Runs.Status}, 'Success')), ...
            '%s experiment runs did not all succeed.', algorithm);

        assert(all(isfinite([Runs.Score])), ...
            '%s experiment contains a non-finite score.', algorithm);

    end

    fprintf('testExperimentProgressCallback passed: %d reports received.\n', ...
        numel(Reports));

    function captureProgress(ProgressInfo)
        Reports(end + 1) = ProgressInfo;
    end

end